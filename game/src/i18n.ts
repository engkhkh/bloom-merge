export function lang(): Lang { return load().lang === 'ar' ? 'ar' : 'en'; }
export function t() { return STR[lang()]; }
export function isRTL() { return lang() === 'ar'; }

export function toggleLang(): Lang {
  const d = load();
  d.lang = d.lang === 'ar' ? 'en' : 'ar';
  save(d);
  return d.lang;
}
